"""Shared guard for tests that read the migrated canonical data tree.

Canonical tables and panels live under `_david/data/conformers/canonical/` and are
deliberately **not** version-controlled: they are several megabytes of study
output that is regenerated by `python -m _david.code.conformer.cli migrate`.
Tests that assert on the real migrated data therefore have to be skipped, not
failed, on a host where the migration has not run yet - and the skip reason tells
the reader exactly which command fixes it.
"""

from __future__ import annotations

import unittest

from _david.code.conformer.core.paths import CANONICAL_ROOT

MIGRATE_HINT = (
    "canonical conformer data is not present on this host "
    f"({CANONICAL_ROOT.as_posix()}); run "
    "`python -m _david.code.conformer.cli migrate` to populate it"
)

# A single cheap probe: the registry table is written last by the migration, so if
# it exists the rest of the tree was written successfully too.
HAS_CANONICAL_DATA = (CANONICAL_ROOT / "tables" / "reference_counts.csv").is_file()

requires_canonical_data = unittest.skipUnless(HAS_CANONICAL_DATA, MIGRATE_HINT)
